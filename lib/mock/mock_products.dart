  static Product _product({
    required String id,
    required String name,
    required String brand,
    required String categoryId,
    required String image,
    List<String>? gallery,
    required int price,
    required int original,
    required double rating,
    required int reviews,
    required int sold,
    required int score,
    required MarketplaceCode best,
    required List<int> markups,
    required String specs,
    required String tagline,
    required String description,
    required String aiSummary,
    required List<String> highlights,
    required List<String> pros,
    required List<String> cons,
    List<String> useCases = const [],
    bool rising = false,
  }) {
    final discount = ((original - price) / original * 100).round();
    final bestMarketplace = MockMarketplaces.byCode(best);
    final others = MockMarketplaces.all.where((m) => m.code != best).toList();

    return Product(
      id: id,
      name: name,
      slug: id,
      description: description,
      tagline: tagline,
      brand: brand,
      categoryId: categoryId,
      imageUrl: image,
      galleryUrls: gallery ?? [image],
      rating: rating,
      reviewCount: reviews,
      soldCount: sold,
      currentPrice: price,
      originalPrice: original,
      discountPercent: discount,
      chotHoiScore: score,
      isGoodDeal: discount >= 12 || score >= 88,
      inStock: true,
      marketplace: bestMarketplace,
      marketplaceProductId: '${best.name}-$id',
      productUrl: _url(best, id),
      affiliateUrl: 'https://chothoi.vn/go/$id',
      specsSummary: specs,
      badges: _defaultBadges,
      useCases: useCases,
      aiSummary: aiSummary,
      aiHighlights: highlights,
      pros: pros,
      cons: cons,
      offers: [
        MarketplaceOffer(marketplace: bestMarketplace, price: price, productUrl: _url(best, id)),
        for (var i = 0; i < others.length; i++)
          MarketplaceOffer(marketplace: others[i], price: price + markups[i], productUrl: _url(others[i].code, id)),
      ],
      priceHistory: _history(price, original, id.hashCode % 7, rising: rising),
    );
  }

  static String _url(MarketplaceCode code, String id) => switch (code) {
    MarketplaceCode.shopee => 'https://shopee.vn/product/$id',
    MarketplaceCode.tiktokShop => 'https://shop.tiktok.com/view/product/$id',
    MarketplaceCode.lazada => 'https://www.lazada.vn/products/$id',
    MarketplaceCode.tiki => 'https://tiki.vn/$id',
  };

  /// Deterministic 90-day curve that ends at [current].
  static List<PriceHistoryPoint> _history(int current, int original, int seed, {bool rising = false}) {
    const days = 90;
    final today = DateTime.now();
    final start = DateTime(today.year, today.month, today.day).subtract(const Duration(days: days - 1));
    final high = current + (original - current) * 0.85;
    final range = high - current;
    final step = current < 2000000 ? 1000 : 10000;
    final floor = rising ? current - range * 0.4 : current.toDouble();

    return [
      for (var i = 0; i < days; i++)
        PriceHistoryPoint(
          date: start.add(Duration(days: i)),
          price: i == days - 1
              ? current
              : () {
                  final t = i / (days - 1);
                  final trend = rising
                      ? current - range * 0.4 * math.sin(math.pi * t)
                      : high - range * math.pow(t, 1.4);
                  final wobble = math.sin(i * 0.45 + seed) * range * 0.18;
                  final value = (trend + wobble).clamp(floor, high);
                  return math.max((value / step).round() * step, floor.round());
                }(),
        ),
    ];
  }
